"""Build the paper. Every number in it comes from a pipeline run, never by hand.

`hof paper` writes `paper/generated/results.tex` from a run's output, then
compiles `paper/main.tex` with Tectonic, which needs no TeX installation.
"""

import io
import json
import platform
import shutil
import subprocess
import tarfile
import urllib.request
import zipfile
from pathlib import Path

import pandas as pd

from hof.data import ROOT

PAPER = ROOT / "paper"
TOOLS = ROOT / ".tools"
TECTONIC_VERSION = "0.17.0"
TECTONIC_TARGETS = {
    ("Windows", "AMD64"): "x86_64-pc-windows-msvc.zip",
    ("Linux", "x86_64"): "x86_64-unknown-linux-musl.tar.gz",
    ("Linux", "aarch64"): "aarch64-unknown-linux-musl.tar.gz",
    ("Darwin", "arm64"): "aarch64-apple-darwin.tar.gz",
    ("Darwin", "x86_64"): "x86_64-apple-darwin.tar.gz",
}


def tectonic(install: bool = True) -> Path | None:
    """Path to Tectonic, downloading the pinned release into .tools/ if needed."""
    exe = TOOLS / ("tectonic.exe" if platform.system() == "Windows" else "tectonic")
    if exe.exists():
        return exe
    if found := shutil.which("tectonic"):
        return Path(found)
    if not install:
        return None
    target = TECTONIC_TARGETS[(platform.system(), platform.machine())]
    url = (
        f"https://github.com/tectonic-typesetting/tectonic/releases/download/"
        f"tectonic%40{TECTONIC_VERSION}/tectonic-{TECTONIC_VERSION}-{target}"
    )
    with urllib.request.urlopen(url) as resp:
        blob = io.BytesIO(resp.read())
    TOOLS.mkdir(exist_ok=True)
    if target.endswith(".zip"):
        zipfile.ZipFile(blob).extractall(TOOLS)
    else:
        tarfile.open(fileobj=blob).extractall(TOOLS, filter="data")
    exe.chmod(0o755)
    return exe


def _tex(s: object) -> str:
    return "".join("\\" + c if c in "&%$#_{}" else c for c in str(s))


def write_results(run: Path) -> Path:
    """Turn a run's output into LaTeX macros and tables the paper can \\input."""
    metrics = json.loads((run / "metrics.json").read_text(encoding="utf-8"))
    rankings = pd.read_csv(run / "rankings.csv")
    m, rule = metrics["model"], metrics["ithf_rule"]
    lines = [
        "% Generated by `hof paper`. Do not edit; change the pipeline instead.",
        f"\\newcommand{{\\SplitYear}}{{{metrics['split_year']}}}",
        f"\\newcommand{{\\AsOf}}{{{metrics['as_of']}}}",
        f"\\newcommand{{\\Threshold}}{{{metrics['threshold']:.2f}}}",
        f"\\newcommand{{\\TestPlayers}}{{{m['players']}}}",
        f"\\newcommand{{\\TestInducted}}{{{m['inducted']}}}",
        "\\newcommand{\\MetricsTable}{%",
        "\\begin{tabular}{lrrrr}\\toprule",
        "Method & Precision & Recall & F1 & AUC \\\\\\midrule",
        f"ITHF auto-ballot rule & {rule['precision']:.3f} & {rule['recall']:.3f} & "
        f"{rule['f1']:.3f} & {rule['auc']:.3f} \\\\",
        f"Career score & {m['precision']:.3f} & {m['recall']:.3f} & "
        f"{m['f1']:.3f} & {m['auc']:.3f} \\\\\\bottomrule",
        "\\end{tabular}}",
        "\\newcommand{\\TopTable}{%",
        "\\begin{tabular}{rlrlll}\\toprule",
        "\\# & Player & Score & Status & Predicted & Inducted \\\\\\midrule",
    ]
    for r in rankings.head(15).itertuples():
        lines.append(
            f"{r.rank} & {_tex(r.name)} & {r.score:.2f} & {r.status} & "
            f"{'yes' if r.predicted else ''} & {'yes' if r.inducted else ''} \\\\"
        )
    lines += ["\\bottomrule\\end{tabular}}", ""]
    out = PAPER / "generated" / "results.tex"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def build(run: Path) -> Path:
    write_results(run)
    exe = tectonic()
    assert exe is not None
    build_dir = PAPER / "build"
    build_dir.mkdir(exist_ok=True)
    subprocess.run([str(exe), "--outdir", str(build_dir), str(PAPER / "main.tex")], check=True)
    return build_dir / "main.pdf"
